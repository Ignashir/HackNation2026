#!/usr/bin/env bash
# Regenerates deploy/nginx/templates/ from backend_latest/docker/nginx/config-templates/.
# Run it again whenever the backend's nginx templates change.
#
# Caddy terminates TLS in front of this nginx, so the generated configs:
#   - listen on plain port 80 (no ssl, no certificates, no IPv6 listeners)
#   - use ${PUBLIC_DOMAIN} instead of mcod.local in server_name and CORS origins
#   - tell the apps the original scheme was https (Caddy already handled TLS)
#   - reach the admin container by name instead of host.docker.internal
# The forum (05) and MailHog (06) templates are skipped: Caddy proxies those directly,
# so nginx still starts when the optional forum is not running.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
src="$here/../../backend_latest/docker/nginx/config-templates"
out="$here/templates"
mkdir -p "$out"

rm -f "$out"/*.template
for f in "$src"/*.template; do
    case "$(basename "$f")" in 05-discourse.*|06-mail.*) continue ;; esac
    sed -E \
        -e '/^[[:space:]]*listen[[:space:]]+\[::\]/d' \
        -e 's/^([[:space:]]*)listen[[:space:]]+443[[:space:]]+ssl;/\1listen 80;/' \
        -e '/^[[:space:]]*ssl_certificate/d' \
        -e 's/server_name([[:space:]]+)([a-z]+\.)?mcod\.local;/server_name\1\2${PUBLIC_DOMAIN};/' \
        -e "s#'http://mcod\.local'#'https://\${PUBLIC_DOMAIN}'#g" \
        -e '/proxy_set_header/ s/\$scheme/https/g' \
        -e 's#http://host\.docker\.internal:8001#${MCOD_NGINX_ADMIN}#g' \
        "$f" |
    # A server block that listened on both 443 and 80 now has "listen 80;" twice.
    awk '/^[[:space:]]*server[[:space:]]*\{/ { seen = 0 }
         /^[[:space:]]*listen 80;/  { if (seen++) next }
         { print }' > "$out/$(basename "$f")"
done

# Trust X-Forwarded-For from Caddy so the apps log real client IPs.
cat > "$out/00-realip.conf.template" <<'EOF'
# Generated by render-templates.sh: requests arrive from Caddy on the Docker network.
set_real_ip_from 172.16.0.0/12;
set_real_ip_from 10.0.0.0/8;
real_ip_header X-Forwarded-For;
real_ip_recursive on;
EOF

echo "Wrote $(ls "$out" | wc -l | tr -d ' ') templates to $out"
