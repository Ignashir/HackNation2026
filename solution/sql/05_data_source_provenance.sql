-- ---------------------------------------------------------------------
-- DATA_SOURCE: one row per upstream source.
-- ---------------------------------------------------------------------
CREATE TABLE data_source (
    source_id        smallint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text      NOT NULL UNIQUE,
    access_method    text      NOT NULL CHECK (access_method IN ('api', 'file', 'scrape', 'wms')),
    licence          text      NOT NULL CHECK (licence IN ('ODbL', 'CC-BY', 'none', 'public-info')),
    base_url         text,
    redistributable  boolean   NOT NULL DEFAULT false
);

COMMENT ON COLUMN data_source.redistributable IS 'false = use for matching/QA only, never republish (e.g. Ratuj z Sercem).';


-- ---------------------------------------------------------------------
-- IMPORT_RUN: one fetch of one source.
-- ---------------------------------------------------------------------
CREATE TABLE import_run (
    run_id           uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    source_id        smallint     NOT NULL REFERENCES data_source (source_id) ON DELETE RESTRICT,
    started_at       timestamptz  NOT NULL DEFAULT now(),
    data_as_of       timestamptz,
    records_fetched  integer      CHECK (records_fetched IS NULL OR records_fetched >= 0),
    status           text         NOT NULL DEFAULT 'running'
                     CHECK (status IN ('running', 'success', 'partial', 'failed'))
);

COMMENT ON COLUMN import_run.data_as_of IS 'Snapshot time reported by the source (e.g. Overpass osm3s.timestamp_osm_base).';

CREATE INDEX import_run_source_idx ON import_run (source_id, started_at DESC);


-- ---------------------------------------------------------------------
-- SOURCE_RECORD: what one source says about one entity, with the full
-- original payload. Matched to an aed_site (nullable until matched).
-- One row per (source, external_id); updated on every run that sees it.
-- ---------------------------------------------------------------------
CREATE TABLE source_record (
    source_record_id    uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    source_id           smallint     NOT NULL REFERENCES data_source (source_id) ON DELETE RESTRICT,
    run_id              uuid         REFERENCES import_run (run_id) ON DELETE SET NULL,
    external_id         text         NOT NULL,
    external_version    integer,
    site_id             uuid         REFERENCES aed_site (site_id) ON DELETE SET NULL,
    match_method        text         CHECK (match_method IN ('exact_id', 'distance+name', 'manual')),
    match_distance_m    real         CHECK (match_distance_m IS NULL OR match_distance_m >= 0),
    raw_payload         jsonb        NOT NULL,
    source_modified_at  timestamptz,
    first_seen_at       timestamptz  NOT NULL DEFAULT now(),
    last_seen_at        timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT source_record_external_uq UNIQUE (source_id, external_id),
    CONSTRAINT source_record_seen_order CHECK (first_seen_at <= last_seen_at),
    CONSTRAINT source_record_match_consistent
        CHECK ((site_id IS NULL) = (match_method IS NULL))
);

COMMENT ON COLUMN source_record.run_id IS 'Most recent import run that produced/updated this record.';
COMMENT ON COLUMN source_record.external_id IS 'Source-native id, e.g. "node/123" (OSM), "168" (Ratuj z Sercem), "inst/33070" (Kraków).';
COMMENT ON COLUMN source_record.external_version IS 'e.g. OSM @osm_version, for change detection.';
COMMENT ON COLUMN source_record.raw_payload IS 'Original record: all OSM tags, parsed HTML fields, TED JSON ...';

CREATE INDEX source_record_site_idx      ON source_record (site_id);
CREATE INDEX source_record_run_idx       ON source_record (run_id);
CREATE INDEX source_record_unmatched_idx ON source_record (source_id) WHERE site_id IS NULL;
CREATE INDEX source_record_payload_gin   ON source_record USING gin (raw_payload jsonb_path_ops);


-- ---------------------------------------------------------------------
-- FIELD_PROVENANCE: which source record supplied each curated field of
-- a site. Needed for ODbL attribution and conflict resolution.
-- ---------------------------------------------------------------------
CREATE TABLE field_provenance (
    site_id           uuid         NOT NULL REFERENCES aed_site (site_id) ON DELETE CASCADE,
    field_name        text         NOT NULL,
    source_record_id  uuid         NOT NULL REFERENCES source_record (source_record_id) ON DELETE CASCADE,
    chosen_at         timestamptz  NOT NULL DEFAULT now(),
    rule              text         NOT NULL CHECK (rule IN ('priority', 'newest', 'manual')),

    PRIMARY KEY (site_id, field_name)
);

COMMENT ON COLUMN field_provenance.field_name IS 'Column of aed_site, e.g. opening_hours_raw.';

CREATE INDEX field_provenance_record_idx ON field_provenance (source_record_id);
